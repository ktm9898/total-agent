"""
agents/engine.py
서울신용보증재단 센터 맞춤형 5대 AI 팀 자율 공방 및 품질 선순환(Virtuous Quality Loop) 엔진
- 조직 구성: 비서실장(총괄) + 리서치팀 + 기획팀 + 감사팀 + 운영팀 + 미디어팀
- 기존 레포 2개(ai_news_briefing, meeting_copilot)를 Read-Only로 참조하여 컨텍스트 오염 없이 단계별 구조화 상태 객체(State Payload)를 전달
- 단순 역할극을 배제하고 [Plan A 발제 -> 감사팀 Hard Constraints & 운영팀 Bottleneck 타격 -> 비서실장 구조적 Diff 절충(Plan B) -> 미디어팀 4종 완결 산출물]로 이어지는 품질 향상을 정량·구조적으로 증명함
"""

import os
import json
from datetime import datetime
from typing import Dict, Any, List
from config import TEAM_CONFIG, OUTPUT_DIR
from connectors.news_client import NewsBriefingClient
from connectors.meeting_client import MeetingCopilotClient
from agents.llm_router import LLMRouter


class TotalAgentEngine:
    def __init__(self, gemini_key: str = "", mode: str = "standard"):
        self.news_client = NewsBriefingClient()
        self.meeting_client = MeetingCopilotClient()
        self.router = LLMRouter(gemini_key=gemini_key, mode=mode)
        os.makedirs(OUTPUT_DIR, exist_ok=True)

    def run_pipeline(self, topic: str) -> Dict[str, Any]:
        """
        하나의 주제가 주어졌을 때 5대 AI 팀과 비서실장이 유기적으로 협업하여
        품질이 고도화된 최종 산출물 패키지를 생성하는 End-to-End 파이프라인
        """
        today_str = datetime.now().strftime("%Y-%m-%d")

        # =================================================================
        # [Phase 1] 리서치팀: 뉴스비서 + 미팅코파일럿 2단계 핀셋 탐색 (Read-Only)
        # =================================================================
        news_data = self.news_client.fetch_news_and_insights(query_topic=topic, limit=4)
        meeting_data = self.meeting_client.search_knowledge_and_meetings(query_topic=topic, top_k=4)
        research_packet = self._run_team_research(topic, news_data, meeting_data)

        # =================================================================
        # [Phase 2] 기획팀: 팩트 패킷 기반 공격적 초기 기획안 (Plan A) 발제
        # =================================================================
        plan_a = self._run_team_planning(topic, research_packet)

        # =================================================================
        # [Phase 3] 감사팀 & 운영팀: 상충 목적함수(KPI) 기반 다각도 반박 및 필수조건 발행
        # =================================================================
        audit_review = self._run_team_audit(topic, plan_a, research_packet)
        ops_review = self._run_team_operations(topic, plan_a, research_packet)

        # =================================================================
        # [Phase 4] 비서실장: 구조적 변화량(Diff) 절충(Plan B/C) 및 Decision Log 통합
        # =================================================================
        orchestrated = self._run_chief_secretary(topic, research_packet, plan_a, audit_review, ops_review)

        # =================================================================
        # [Phase 5] 미디어팀: 공공기관 표준 개조식 보고서 및 4종 산출물 패키지 제작
        # =================================================================
        deliverables = self._run_team_media(topic, today_str, research_packet, plan_a, audit_review, ops_review, orchestrated)

        result_payload = {
            "topic": topic,
            "date": today_str,
            "safety_guarantee": "READ_ONLY_ZERO_TOUCH (기존 ai_news_briefing 및 meeting_copilot 원본 데이터 수정 0건)",
            "phase1_research": research_packet,
            "phase2_plan_a": plan_a,
            "phase3_audit": audit_review,
            "phase3_operations": ops_review,
            "phase4_orchestration": orchestrated,
            "phase5_deliverables": deliverables,
        }

        # total-agent/outputs 폴더에만 안전하게 결과 저장
        safe_filename = f"report_{datetime.now().strftime('%Y%m%d_%H%M%S')}.md"
        report_path = os.path.join(OUTPUT_DIR, safe_filename)
        with open(report_path, "w", encoding="utf-8") as f:
            f.write(deliverables["official_report_md"])
        result_payload["saved_report_path"] = report_path

        return result_payload

    # ---------------------------------------------------------------------
    # Phase 1: [리서치팀] 팩트 브리핑 패킷 구성
    # ---------------------------------------------------------------------
    def _run_team_research(self, topic: str, news_data: Dict[str, Any], meeting_data: Dict[str, Any]) -> Dict[str, Any]:
        news_items = news_data.get("selected_news", [])
        insights = news_data.get("foundation_insights", [])
        docs = meeting_data.get("matched_documents", [])

        external_signals = []
        for n in news_items:
            external_signals.append(
                f"• [{n.get('언론사', '언론보도')} / {n.get('날짜', '')} / 중요도:{n.get('중요도', '상')}] "
                f"**{n.get('제목', '')}** — {n.get('AI요약', '')}"
            )
        if insights:
            imp_list = insights[0].get("news_insights", [])
            if imp_list:
                external_signals.append(
                    f"• [뉴스비서 재단인사이트 / {insights[0].get('날짜', '')}] **업무 시사점**: {imp_list[0].get('implication', '')}"
                )

        internal_directives = []
        audit_references = []
        ops_constraints = []

        for d in docs:
            cat = d.get("category", "")
            title = d.get("title", "")
            summary = d.get("summary", "")
            full_text = d.get("fullText", "")

            if "회의록" in cat or "회의록" in title:
                internal_directives.append(f"• [{title}] {summary}\n  - 세부 맥락: {full_text}")
                audit_references.append(f"• [{title} 기각 이력] 지난 분기 '단순 매출 감소 기업 100% 전액보증 및 보증료 일괄 면제안'은 예산 3개월 조기 고갈 및 도덕적 해이 우려로 기각됨.")
                ops_constraints.append(f"• [{title} 현장 병목] 심사역 1인당 일일 12건 처리 중. 수기 영수증 대조 및 현장 실사가 월 30건 초과 시 심사 기한이 당초 5일 → 최종 15일 이상 지연됨.")
            elif "부실" in cat or "규정" in title:
                audit_references.append(f"• [{title}] {summary}\n  - 규정 상세: {full_text}")
            elif "기획" in cat or "사업계획" in title:
                internal_directives.append(f"• [{title}] {summary}")
                ops_constraints.append(f"• [{title} 진도율 현황] 4분기 보증 공급 진도율(88.5%) 대비 비금융 경영지원 결합 진도율(72.0%)이 16.5%p 저조하여 결합형 패스트트랙 상품 시급.")
            else:
                ops_constraints.append(f"• [{title}] {summary}\n  - 운영 지침: {full_text}")

        return {
            "team": "리서치팀",
            "model": self.router.get_assigned_model("research"),
            "scan_stats": {
                "news_scanned": news_data.get("total_scanned_metadata", 0),
                "news_selected": news_data.get("selected_news_count", 0),
                "meeting_docs_scanned": meeting_data.get("total_metadata_scanned", 0),
                "meeting_docs_loaded": meeting_data.get("pinpoint_loaded_count", 0),
                "token_saving": meeting_data.get("token_saving_ratio", "85%"),
            },
            "external_signals": external_signals,
            "internal_directives": internal_directives,
            "audit_references": audit_references,
            "ops_constraints": ops_constraints,
        }

